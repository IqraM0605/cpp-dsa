#include <iostream>
using namespace std;
int main()
{
    int num1, num2, sum;

    // Taking input
    cout << "Enter first number: ";
    cin >> num1;

    cout << "Enter second number: ";
    cin >> num2;

    // Calculating sum
    sum = num1 + num2;

    // Displaying result
    cout << "Sum = " << sum << endl;

    return 0;
}